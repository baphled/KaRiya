// Package uikit provides the UI component library for the TUI application.
//
// # Overview
//
// The uikit package is the root of the component library. It organizes
// components into logical subpackages based on their purpose and
// abstraction level.
//
// # Subpackages
//
//   - containers: Layout containers (Box, Overlay)
//   - display: Display components (Logo)
//   - feedback: Modal and feedback components
//   - layout: Screen layout components
//   - navigation: Navigation helpers
//   - primitives: Base UI primitives (text, buttons, badges)
//   - selectors: Selection components
//   - theme: Theme integration
//   - widgets: Higher-level composite components
//
// # Usage
//
// Import specific subpackages:
//
//	import "github.com/baphled/kariya/internal/cli/uikit/primitives"
//	import "github.com/baphled/kariya/internal/cli/uikit/layout"
//
// For detailed documentation, see docs/UIKIT_GUIDE.md.
package uikit
