// Package components provides reusable UI components for the TUI application.
//
// # Overview
//
// The components package contains shared UI elements that can be used across
// multiple screens and intents. These components are built on top of the
// uikit primitives and provide higher-level functionality.
//
// # Available Components
//
//   - Modal overlays and dialogs
//   - Form components and inputs
//   - Navigation elements
//   - Feedback components (loading, error, success states)
//
// # Migration Note
//
// This package is being deprecated in favor of more specific packages:
//   - Use uikit/feedback for modals
//   - Use uikit/primitives for base components
//   - Use uikit/layout for layout components
//
// New code should prefer the uikit subpackages over this legacy package.
package components
